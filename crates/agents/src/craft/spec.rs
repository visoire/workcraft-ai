//! Static `AppSpec` registry for all 17 ArtCraft applications.

use std::time::Duration;

use serde::{Deserialize, Serialize};

/// Connection mode per Craft application (D3).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "lowercase")]
pub enum CraftMode {
    /// `<app>-cli mcp ...` runs an in-process headless engine on files; no GUI window opens.
    #[default]
    Headless,
    /// `<app> --control <port>` runs on screen and `<app>-cli mcp` bridges to that window.
    Live,
    /// Disabled: not connected and not auto-activated.
    Off,
}

impl CraftMode {
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Headless => "headless",
            Self::Live => "live",
            Self::Off => "off",
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        match s.trim().to_ascii_lowercase().as_str() {
            "headless" => Some(Self::Headless),
            "live" => Some(Self::Live),
            "off" => Some(Self::Off),
            _ => None,
        }
    }
}

/// Priority tier from `PLAN.md` section 4.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Tier {
    Existing,
    A,
    B,
    C,
}

/// How headless `<app>-cli mcp` confines file reads and writes (D9).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RootsPolicy {
    /// Server takes no root flags (`gridcraft`, `lightcraft`, `filmcraft`, `effectcraft`, `cadcraft`).
    None,
    /// Single `--automation-read-root <R> --automation-write-root <W>` (`wordcraft`, `pdfcraft`, `photocraft`).
    SingleAutomation,
    /// Repeatable `--automation-read-root <R>... --automation-write-root <W>...` (`deckcraft`, `vectorcraft`, `designcraft`, `soundcraft`, `figcraft`).
    RepeatableAutomation,
    /// Single `--read-root <R> --write-root <W>`, and tool file/dir arguments must be relative forward-slash paths (`texturecraft`, `materialcraft`).
    RelativeReadWrite,
    /// Repeatable `--allow-path <DIR>...` (`solidcraft`).
    AllowPath,
    /// `--clean-room --inbox <DIR>` (`craft-anything`).
    CleanRoomInbox,
}

/// How `<app>-cli mcp` attaches to a live `<app> --control <port>` window.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LiveBridgeKind {
    None,
    /// `mcp --connect <port>`
    ConnectBarePort,
    /// `mcp --connect 127.0.0.1:<port>`
    ConnectHostPort,
    /// `mcp --connect 127.0.0.1:<port> --compact`
    ConnectHostPortCompact,
    /// `mcp --bridge <port>`
    BridgeBarePort,
    /// `mcp --bridge 127.0.0.1:<port>`
    BridgeHostPort,
    /// `mcp --bridge 127.0.0.1:<port> --control-token-file <path>`
    BridgeHostPortTokenFile,
    /// `mcp --attach <port>`
    AttachBarePort,
}

/// How the desktop window and CLI authenticate over the loopback control socket (T1.6).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LiveAuth {
    /// Loopback TCP without a token (`deckcraft`, `designcraft`, `effectcraft`, `figcraft`, `lightcraft`, `soundcraft`, `vectorcraft`, `solidcraft`).
    None,
    /// GUI writes `%APPDATA%\<Name>\control-key.local-<port>` (or `~/.config/<id>/...`); CLI reads it automatically (`wordcraft`).
    ControlKeyFile,
    /// GUI writes `%USERPROFILE%\.gridcraft\control-<port>.token`; CLI reads it automatically (`gridcraft`).
    HomeDotTokenFile,
    /// GUI writes `%LOCALAPPDATA%\cadcraft-control-<port>.token`; CLI reads it automatically (`cadcraft`).
    LocalAppDataTokenFile,
    /// GUI writes `%TEMP%\<id>-control-<port>.token` or reads `env_var`; CLI reads `--token` / `env_var` / temp file (`texturecraft`, `materialcraft`).
    TempTokenFile {
        env_var: &'static str,
        no_prefs_env: &'static str,
    },
    /// GUI and CLI both require an explicit `--control-token-file <path>` (`photocraft`).
    ExplicitTokenFile,
    /// Both GUI and CLI require a 64-hex-digit token in `env_var` (`filmcraft`).
    MandatoryEnvHex64 { env_var: &'static str },
}

/// Target native tool or generic command for one `craft_*` facade verb (section 5.3).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum VerbTarget {
    None,
    /// Direct MCP tool name on the server, e.g. `"doc_open"`.
    Tool(&'static str),
    /// Generic command runner, e.g. `command_run { id: "file.new", params: ... }`.
    Command {
        runner: &'static str,
        id_field: &'static str,
        cmd_id: &'static str,
        params_field: &'static str,
    },
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct VerbMap {
    pub open: VerbTarget,
    pub new: VerbTarget,
    pub save: VerbTarget,
    pub inspect: VerbTarget,
    pub render: VerbTarget,
    pub export: VerbTarget,
    pub commands: &'static str,
    pub run: &'static str,
    pub batch: &'static str,
}

impl VerbMap {
    pub const NONE: Self = Self {
        open: VerbTarget::None,
        new: VerbTarget::None,
        save: VerbTarget::None,
        inspect: VerbTarget::None,
        render: VerbTarget::None,
        export: VerbTarget::None,
        commands: "",
        run: "",
        batch: "",
    };
}

/// Authoritative specification of one ArtCraft application.
#[derive(Debug, Clone, Copy)]
pub struct AppSpec {
    pub id: &'static str,
    pub name: &'static str,
    pub kind: &'static str,
    pub tier: Tier,
    pub always_on_default: bool,
    pub off_by_default: bool,
    pub install_dirs: &'static [&'static str],
    pub cli: &'static str,
    pub gui: &'static str,
    pub env_override: &'static str,
    pub aliases: &'static [&'static str],
    pub headless_extra_args: &'static [&'static str],
    pub roots: RootsPolicy,
    pub port: Option<u16>,
    pub live_bridge: LiveBridgeKind,
    pub auth: LiveAuth,
    pub lean_tools: &'static [&'static str],
    pub live_only_tools: &'static [&'static str],
    pub default_timeout_secs: u64,
    pub tool_timeouts: &'static [(&'static str, u64)],
    pub reads_formats: &'static [&'static str],
    pub writes_formats: &'static [&'static str],
    pub icon: &'static str,
    pub skill: &'static str,
    pub specialist: &'static str,
    pub verbs: VerbMap,
}

impl AppSpec {
    #[must_use]
    pub fn supports_live(&self) -> bool {
        self.port.is_some() && !matches!(self.live_bridge, LiveBridgeKind::None)
    }

    #[must_use]
    pub fn timeout_for(&self, subtool: &str) -> Duration {
        let secs = self
            .tool_timeouts
            .iter()
            .find_map(|(name, s)| (*name == subtool).then_some(*s))
            .unwrap_or(self.default_timeout_secs);
        Duration::from_secs(secs)
    }
}

