#[must_use]
pub fn specs() -> &'static [AppSpec] {
    &SPECS
}

#[must_use]
pub fn spec_by_id(id: &str) -> Option<&'static AppSpec> {
    let clean = id.trim().to_ascii_lowercase();
    SPECS.iter().find(|s| s.id == clean)
}

#[must_use]
pub fn find_spec(raw: &str) -> Option<&'static AppSpec> {
    let clean = raw.trim().to_ascii_lowercase();
    if clean.is_empty() {
        return None;
    }
    SPECS.iter().find(|s| {
        s.id == clean
            || s.name.to_ascii_lowercase() == clean
            || s.id.strip_suffix("craft") == Some(clean.as_str())
            || s.aliases.contains(&clean.as_str())
    })
}
